//! Lichtwart Demo Simulator — Tauri backend.
//!
//! Module map (see `docs/ARCHITECTURE.md` for the full contract):
//! - [`commands`]: every `#[tauri::command]` (IPC entry points, thin adapters), one file per area
//! - [`events`]: every event emitted to the frontend
//! - [`model`]: every serde type crossing IPC + the library file format
//! - [`error`]: the single serializable [`error::AppError`]
//! - [`state`]: [`state::AppState`] managed by Tauri
//! - [`c8y`]: Cumulocity HTTP/realtime client, credentials, activity log
//! - [`library`]: bundled library loading, validation, selection
//! - [`payload`]: native Core v2 naming + payload builders (pure)
//! - [`sim`]: session task, generators, scheduler, operations, faults
//! - [`device`]: demo device CRUD, `lw_demo`, apply, floorplans, export, upgrade
//! - [`raw`]: raw fire panel

