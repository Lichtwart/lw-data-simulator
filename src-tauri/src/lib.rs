/// The tauri-specta builder: single registry of all commands and events.
/// Used at runtime (invoke handler, event mounting) and by the `export_bindings`
/// test that writes `src/lib/bindings.ts`.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(commands::collect())
        .events(events::collect())
}

/// Path of the generated TypeScript bindings, relative to `src-tauri/`.
pub const BINDINGS_PATH: &str = "../src/lib/bindings.ts";

/// Export TypeScript bindings for all commands, events and types.
pub fn export_bindings(path: &std::path::Path) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// @ts-nocheck\n// Generated by tauri-specta — do not edit. Run `npm run gen:types`."),
            path,
        )
        .map_err(|e| e.to_string())
}

/// App entry point (called from `main.rs`).
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();

    tauri::Builder::default()
        .plugin(
            tauri_plugin_log::Builder::new()
                .level(log::LevelFilter::Info)
                .build(),
        )
        .plugin(tauri_plugin_updater::Builder::new().build())
        .plugin(tauri_plugin_process::init())
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);

            if let Err(e) = c8y::credentials::init_store() {
                log::warn!("credential store unavailable: {e}");
            }

            let version = app.package_info().version.to_string();
            let root = app
                .path()
                .resolve("library", BaseDirectory::Resource)
                .map_err(|e| error::AppError::Library(e.to_string()));
            let library = root.and_then(|r| library::loader::load(&r, &version));
            if let Err(e) = &library {
                log::error!("library failed to load: {e}");
            }
            app.manage(AppState::new(library));
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building tauri application")
        .run(|app, event| {
            // Quitting must not leave EXECUTING operations (the plugin has no timeout for them)
            // or the advisory lock behind: stop the session first, then really exit.
            if let tauri::RunEvent::ExitRequested { api, .. } = &event {
                static QUITTING: std::sync::atomic::AtomicBool =
                    std::sync::atomic::AtomicBool::new(false);
                if QUITTING.swap(true, std::sync::atomic::Ordering::SeqCst) {
                    return; // the exit we asked for below
                }
                api.prevent_exit();
                let app = app.clone();
                tauri::async_runtime::spawn(async move {
                    app.state::<AppState>().stop_for_exit(&app).await;
                    app.exit(0);
                });
            }
        });
}

#[cfg(test)]
mod tests {
    /// Regenerates `src/lib/bindings.ts` (`npm run gen:types`). Also runs as part of
    /// `cargo test`, so CI can fail on `git diff --exit-code src/lib/bindings.ts`.
    #[test]
    fn export_bindings() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(super::BINDINGS_PATH);
        super::export_bindings(&path).expect("export bindings");
    }
}
